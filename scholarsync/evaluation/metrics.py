# AGGREGATE EVALUATION
# ══════════════════════════════════════════════════════════════════════════

def compute_all_metrics(
    generated_text: str,
    generated_claims: list[str],
    source_chunks: list[str],
    paper_titles: list[str],
    retrieval_relevance_scores: list[float] | None = None,
    retrieval_relevant_flags: list[bool] | None = None,
    total_relevant_in_corpus: int = 0,
) -> dict:
    """
    Compute all evaluation metrics from actual data.
    
    Returns dict with all 14 metric scores + overall quality.
    """
    # Split generated text into sentences
    generated_sentences = [
        s.strip() for s in re.split(r'[.!?]\s+', generated_text)
        if len(s.strip()) > 10
    ]
    
    # Retrieval metrics (if retrieval data provided)
    ndcg = 0.0
    precision_k = 0.0
    recall_k = 0.0
    mrr = 0.0
    map_score = 0.0
    
    if retrieval_relevance_scores:
        ndcg = compute_ndcg(retrieval_relevance_scores, k=10)
        
    if retrieval_relevant_flags:
        precision_k = compute_precision_at_k(retrieval_relevant_flags, k=5)
        recall_k = compute_recall_at_k(
            retrieval_relevant_flags, total_relevant_in_corpus or len(retrieval_relevant_flags), k=10
        )
        mrr = compute_mrr(retrieval_relevant_flags)
        map_score = compute_map(retrieval_relevant_flags)
    
    # Generation quality metrics
    faithfulness = compute_faithfulness_score(generated_claims, source_chunks)
    citation_alignment = compute_citation_alignment(generated_text, paper_titles, source_chunks)
    semantic_grounding = compute_semantic_grounding(generated_text, source_chunks)
    context_utilization = compute_context_utilization(generated_text, source_chunks)
    redundancy_reduction = compute_redundancy_reduction(generated_sentences)
    retrieval_diversity = compute_retrieval_diversity(source_chunks)
    semantic_coherence = compute_semantic_coherence(generated_sentences)
    cross_doc_synthesis = compute_cross_document_synthesis(generated_text, paper_titles)
    
    # Overall quality (weighted average of generation metrics)
    generation_metrics = [
        faithfulness,
        citation_alignment,
        semantic_grounding,
        context_utilization,
        redundancy_reduction,
        semantic_coherence,
        cross_doc_synthesis,
    ]
    overall_quality = round(sum(generation_metrics) / len(generation_metrics), 4)
    
    metrics = {
        # Retrieval metrics
        "ndcg_at_10": ndcg,
        "precision_at_5": precision_k,
        "recall_at_10": recall_k,
        "mrr": mrr,
        "map": map_score,
        # Generation metrics
        "faithfulness": faithfulness,
        "citation_alignment": citation_alignment,
        "semantic_grounding": semantic_grounding,
        "context_utilization": context_utilization,
        "redundancy_reduction": redundancy_reduction,
        "retrieval_diversity": retrieval_diversity,
        "semantic_coherence": semantic_coherence,
        "cross_document_synthesis": cross_doc_synthesis,
        # Overall
        "overall_quality": overall_quality,
    }
    
    logger.info("Evaluation metrics computed: overall=%.3f", overall_quality)
    return metrics
