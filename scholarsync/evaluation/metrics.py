# GENERATION QUALITY METRICS — computed from actual text comparison
# ══════════════════════════════════════════════════════════════════════════

def _tokenize(text: str) -> list[str]:
    """Simple word tokenization."""
    return re.findall(r'\b\w{2,}\b', text.lower())


def _ngrams(tokens: list[str], n: int) -> list[tuple]:
    """Generate n-grams from token list."""
    return [tuple(tokens[i:i+n]) for i in range(len(tokens) - n + 1)]


def compute_faithfulness_score(
    generated_claims: list[str],
    source_chunks: list[str],
) -> float:
    """
    Faithfulness Score — measures whether generated claims are grounded in evidence.
    
    Uses token overlap between each claim and source chunks.
    A claim is "grounded" if it has >50% token overlap with at least one source chunk.
    
    Args:
        generated_claims: List of claims/sentences from generated output
        source_chunks: List of retrieved source texts
    
    Returns:
        Score in [0.0, 1.0] — fraction of claims that are grounded
    """
    if not generated_claims:
        return 1.0  # No claims = nothing unfaithful
    if not source_chunks:
        return 0.0  # No sources = everything is ungrounded
    
    source_tokens = set()
    for chunk in source_chunks:
        source_tokens.update(_tokenize(chunk))
    
    grounded_count = 0
    for claim in generated_claims:
        claim_tokens = set(_tokenize(claim))
        if not claim_tokens:
            grounded_count += 1
            continue
        overlap = len(claim_tokens & source_tokens) / len(claim_tokens)
        if overlap >= 0.4:  # At least 40% of claim tokens found in sources
            grounded_count += 1
    
    return round(grounded_count / len(generated_claims), 4)


def compute_citation_alignment(
    generated_text: str,
    cited_paper_titles: list[str],
    source_chunks: list[str],
) -> float:
    """
    Citation Alignment Score — measures whether citations truly support claims.
    
    Checks if cited paper names actually appear in the retrieved source context.
    
    Args:
        generated_text: Full generated output text
        cited_paper_titles: Paper titles referenced in citations
        source_chunks: Retrieved source chunk texts
    
    Returns:
        Score in [0.0, 1.0]
    """
    if not cited_paper_titles:
        return 1.0  # No citations to misalign
    
    combined_sources = " ".join(source_chunks).lower()
    
    aligned_count = 0
    for title in cited_paper_titles:
        # Check if paper title (or significant portion) appears in sources
        title_tokens = set(_tokenize(title))
        source_tokens_set = set(_tokenize(combined_sources))
        if not title_tokens:
            aligned_count += 1
            continue
        overlap = len(title_tokens & source_tokens_set) / len(title_tokens)
        if overlap >= 0.5:
            aligned_count += 1
    
    return round(aligned_count / len(cited_paper_titles), 4)


def compute_semantic_grounding(
    generated_text: str,
    source_chunks: list[str],
) -> float:
    """
    Semantic Grounding Score — measures token-level overlap between
    generated output and retrieved evidence (unigram + bigram).
    
    Higher score = more of the generated content is supported by sources.
    
    Args:
        generated_text: Full generated output
        source_chunks: Retrieved source texts
    
    Returns:
        Score in [0.0, 1.0]
    """
    if not generated_text or not source_chunks:
        return 0.0
    
    gen_tokens = _tokenize(generated_text)
    source_text = " ".join(source_chunks)
    src_tokens = _tokenize(source_text)
    
    if not gen_tokens or not src_tokens:
        return 0.0
    
    # Unigram overlap
    gen_set = set(gen_tokens)
    src_set = set(src_tokens)
    unigram_overlap = len(gen_set & src_set) / len(gen_set) if gen_set else 0
    
    # Bigram overlap
    gen_bigrams = set(_ngrams(gen_tokens, 2))
    src_bigrams = set(_ngrams(src_tokens, 2))
    bigram_overlap = len(gen_bigrams & src_bigrams) / len(gen_bigrams) if gen_bigrams else 0
    
    # Weighted average (bigrams are more meaningful)
    return round(unigram_overlap * 0.4 + bigram_overlap * 0.6, 4)


def compute_context_utilization(
    generated_text: str,
    source_chunks: list[str],
) -> float:
    """
    Context Utilization Score — measures how effectively retrieved chunks
    are actually used in generation.
    
    Fraction of source chunks that have meaningful overlap with generated text.
    
    Args:
        generated_text: Full generated output
        source_chunks: Retrieved source texts
    
    Returns:
        Score in [0.0, 1.0]
    """
    if not source_chunks:
        return 0.0
    if not generated_text:
        return 0.0
    
    gen_tokens = set(_tokenize(generated_text))
    utilized = 0
    
    for chunk in source_chunks:
        chunk_tokens = set(_tokenize(chunk))
        if not chunk_tokens:
            continue
        overlap = len(chunk_tokens & gen_tokens) / len(chunk_tokens)
        if overlap >= 0.15:  # At least 15% of chunk tokens used
            utilized += 1
    
    return round(utilized / len(source_chunks), 4)


def compute_redundancy_reduction(generated_sentences: list[str]) -> float:
    """
    Redundancy Reduction Score — measures how effectively repetitive
    insights are removed from the output.
    
    Uses pairwise token overlap to detect near-duplicate sentences.
    Higher score = less redundancy.
    
    Args:
        generated_sentences: List of sentences in generated output
    
    Returns:
        Score in [0.0, 1.0] — 1.0 means no redundancy
    """
    if len(generated_sentences) <= 1:
        return 1.0
    
    redundant_pairs = 0
    total_pairs = 0
    
    for i in range(len(generated_sentences)):
        tokens_i = set(_tokenize(generated_sentences[i]))
        if len(tokens_i) < 3:
            continue
        for j in range(i + 1, len(generated_sentences)):
            tokens_j = set(_tokenize(generated_sentences[j]))
            if len(tokens_j) < 3:
                continue
            total_pairs += 1
            overlap = len(tokens_i & tokens_j) / min(len(tokens_i), len(tokens_j))
            if overlap >= 0.7:  # 70%+ overlap = redundant
                redundant_pairs += 1
    
    if total_pairs == 0:
        return 1.0
    
    redundancy_rate = redundant_pairs / total_pairs
    return round(1.0 - redundancy_rate, 4)


def compute_retrieval_diversity(source_chunks: list[str]) -> float:
    """
    Retrieval Diversity Score — measures whether retrieval includes
    diverse perspectives (not all from same region of corpus).
    
    Uses token distinctiveness across chunks.
    
    Args:
        source_chunks: Retrieved source texts
    
    Returns:
        Score in [0.0, 1.0] — higher = more diverse
    """
    if len(source_chunks) <= 1:
        return 1.0
    
    # Compute pairwise Jaccard distances
    token_sets = [set(_tokenize(chunk)) for chunk in source_chunks]
    
    distances = []
    for i in range(len(token_sets)):
        for j in range(i + 1, len(token_sets)):
            if not token_sets[i] or not token_sets[j]:
                distances.append(1.0)
                continue
            jaccard = len(token_sets[i] & token_sets[j]) / len(token_sets[i] | token_sets[j])
            distances.append(1.0 - jaccard)  # Distance = 1 - similarity
    
    if not distances:
        return 1.0
    
    avg_distance = sum(distances) / len(distances)
    return round(avg_distance, 4)


def compute_semantic_coherence(generated_sentences: list[str]) -> float:
    """
    Semantic Coherence Score — measures logical consistency and continuity
    across generated sections.
    
    Uses adjacent-sentence token overlap as a proxy for topic flow.
    
    Args:
        generated_sentences: Ordered list of sentences in generated output
    
    Returns:
        Score in [0.0, 1.0] — higher = more coherent transitions
    """
    if len(generated_sentences) <= 1:
        return 1.0
    
    adjacency_scores = []
    for i in range(len(generated_sentences) - 1):
        tokens_i = set(_tokenize(generated_sentences[i]))
        tokens_j = set(_tokenize(generated_sentences[i + 1]))
        
        if not tokens_i or not tokens_j:
            continue
        
        # Moderate overlap between adjacent sentences indicates coherent flow
        overlap = len(tokens_i & tokens_j) / max(len(tokens_i), len(tokens_j))
        # Ideal: 15-50% overlap (too low = disjointed, too high = repetitive)
        if overlap < 0.15:
            adjacency_scores.append(overlap / 0.15)  # Penalize low coherence
        elif overlap > 0.5:
            adjacency_scores.append(max(0.5, 1.0 - (overlap - 0.5)))  # Penalize high overlap
        else:
            adjacency_scores.append(1.0)  # Good range
    
    if not adjacency_scores:
        return 0.5
    
    return round(sum(adjacency_scores) / len(adjacency_scores), 4)


def compute_cross_document_synthesis(
    generated_text: str,
    paper_titles: list[str],
) -> float:
    """
    Cross-Document Synthesis Score — measures how effectively the system
    integrates insights from multiple papers.
    
    Checks how many papers are referenced/used in the generated output.
    
    Args:
        generated_text: Full generated output
        paper_titles: List of available paper titles
    
    Returns:
        Score in [0.0, 1.0] — higher = better multi-paper integration
    """
    if not paper_titles:
        return 1.0
    if not generated_text:
        return 0.0
    
    gen_lower = generated_text.lower()
    referenced_count = 0
    
    for title in paper_titles:
        # Check if significant words from title appear in output
        title_tokens = _tokenize(title)
        significant_tokens = [t for t in title_tokens if len(t) > 3]
        if not significant_tokens:
            referenced_count += 1
            continue
        
        matches = sum(1 for t in significant_tokens if t in gen_lower)
        if matches >= max(1, len(significant_tokens) * 0.4):
            referenced_count += 1
    
    return round(referenced_count / len(paper_titles), 4)


