def compute_ndcg(relevance_scores: list[float], k: int = 10) -> float:
    """
    Normalized Discounted Cumulative Gain @ K.
    
    Measures ranking quality: are highly relevant chunks ranked earlier?
    
    Args:
        relevance_scores: Ordered list of relevance scores [0.0-1.0] for retrieved chunks
        k: Cutoff rank
    
    Returns:
        nDCG score in [0.0, 1.0]
    """
    if not relevance_scores:
        return 0.0
    
    scores = relevance_scores[:k]
    
    # DCG: sum of rel_i / log2(i+1)
    dcg = sum(
        rel / math.log2(i + 2)  # i+2 because i is 0-indexed
        for i, rel in enumerate(scores)
    )
    
    # Ideal DCG: sorted scores
    ideal_scores = sorted(relevance_scores, reverse=True)[:k]
    idcg = sum(
        rel / math.log2(i + 2)
        for i, rel in enumerate(ideal_scores)
    )
    
    if idcg == 0:
        return 0.0
    
    return round(dcg / idcg, 4)


def compute_precision_at_k(relevant_flags: list[bool], k: int = 5) -> float:
    """
    Precision@K — fraction of top-K retrieved chunks that are relevant.
    
    Args:
        relevant_flags: Boolean list indicating relevance of each retrieved chunk
        k: Cutoff rank
    
    Returns:
        Precision score in [0.0, 1.0]
    """
    if not relevant_flags:
        return 0.0
    
    top_k = relevant_flags[:k]
    return round(sum(top_k) / len(top_k), 4)


def compute_recall_at_k(
    relevant_flags: list[bool],
    total_relevant: int,
    k: int = 10,
) -> float:
    """
    Recall@K — fraction of all relevant chunks that appear in top-K.
    
    Args:
        relevant_flags: Boolean list indicating relevance of each retrieved chunk
        total_relevant: Total number of relevant chunks in the corpus
        k: Cutoff rank
    
    Returns:
        Recall score in [0.0, 1.0]
    """
    if total_relevant == 0:
        return 0.0
    
    top_k = relevant_flags[:k]
    retrieved_relevant = sum(top_k)
    return round(retrieved_relevant / total_relevant, 4)


def compute_mrr(relevant_flags: list[bool]) -> float:
    """
    Mean Reciprocal Rank — how early the first relevant chunk appears.
    
    Args:
        relevant_flags: Boolean list indicating relevance of each retrieved chunk
    
    Returns:
        MRR score in [0.0, 1.0]
    """
    for i, is_relevant in enumerate(relevant_flags):
        if is_relevant:
            return round(1.0 / (i + 1), 4)
    return 0.0


def compute_map(relevant_flags: list[bool]) -> float:
    """
    Mean Average Precision — average precision at each relevant position.
    
    Args:
        relevant_flags: Boolean list indicating relevance of each retrieved chunk
    
    Returns:
        MAP score in [0.0, 1.0]
    """
    if not relevant_flags or not any(relevant_flags):
        return 0.0
    
    precisions = []
    relevant_count = 0
    
    for i, is_relevant in enumerate(relevant_flags):
        if is_relevant:
            relevant_count += 1
            precisions.append(relevant_count / (i + 1))
    
    if not precisions:
        return 0.0
    
    return round(sum(precisions) / len(precisions), 4)


